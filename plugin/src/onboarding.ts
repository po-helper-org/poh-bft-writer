/**
 * Онбординг первого запуска (US-5–8, 42): чистая половина без ввода-вывода.
 *
 * Слайды — данные, а не разметка: браузерная половина рендерит их одинаково,
 * тесты проверяют состав, а хост отдаёт по RPC. Ключ Z.AI валидируется по
 * форме, проверяется сетевым вызовом на хосте, а хранится файлом в DSH_HOME
 * (`zai.key`): запись в harness/.env с хоста контейнера невозможна (файл живёт
 * у compose на машине), поэтому entrypoint подмешивает ключ в окружение при
 * рестарте — и «перезапустить веб-сервис» из подсказки делает ключ активным.
 */

/**
 * Форма ключа Z.AI: `id.secret` из двух частей букв-цифр смешанного регистра
 * (живой ключ из консоли Z.AI не сводится к hex — проверено на ключе
 * формата …EGaG); событие валидации — форма, истина — сетевая проверка.
 */
const ZAI_KEY = /^[0-9A-Za-z_-]{16,}\.[0-9A-Za-z_-]{16,}$/

export const ZAI_KEY_FILE = 'zai.key'

