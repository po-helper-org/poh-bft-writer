export type DictationMode = 'browser' | 'local'

/** Вердикт формы ключа до сетевой проверки. */
export function validateZaiKey(raw: string): { ok: boolean; reason?: string } {
  const key = raw.trim()
  if (!key) return { ok: false, reason: 'Пусто: вставьте ключ из консоли Z.AI' }
  if (!ZAI_KEY.test(key)) return { ok: false, reason: 'Не похож на ключ Z.AI: ожидается форма id.secret (две части через точку)' }
  return { ok: true }
}

/** Что возвращает хост по подкоманде state: минимум для клиентского решения. */
export interface OnboardingState {
  /** Онбординг пройден или пропущен — оверлей не показывать. */
  done: boolean
  /** Ключ лежит в DSH_HOME (значение наружу не отдаём — только факт). */
  hasKey: boolean
  /** Ключ уже в окружении процесса — рестарт не нужен. */
  keyActive: boolean
  dictation: DictationMode
}

/** Текст подсказки о рестарте — одна формулировка для UI и логов. */
export function restartHint(): string {
  return 'Ключ сохранён. Перезапустите веб-сервис командой docker compose restart harness-web (в каталоге harness/) — и он заработает.'
}

/**
 * Ответ сетевой проверки ключа. Хост делает один запрос к каталогу моделей:
 * это самая дешёвая операция, не тратящая токены.
 */
export interface KeyCheckResult {
  ok: boolean
  /** Человеческая причина отказа — на карточку, не в консоль. */
  message: string
}

export function keyCheckFromStatus(status: number): KeyCheckResult {
  if (status === 200) return { ok: true, message: 'Ключ работает' }
  if (status === 401 || status === 403) return { ok: false, message: 'Ключ отклонён (401/403): проверьте значение или создайте новый в консоли Z.AI' }
  return { ok: false, message: `Z.AI ответил ${status}: попробуйте ещё раз позже` }
}
